export type Dictionary = typeof dictionaries.en

export function getDictionary(language?: string | null): Dictionary {
  return dictionaries[normalizeLocale(language)] as Dictionary
}

export function statusLabel(status: string, language?: string | null) {
  const common = getDictionary(language).common
  const labels: Record<string, string> = {
    pending: common.pending,
    booked: normalizeLocale(language) === "ar" ? "محجوز" : "Booked",
    confirmed: common.confirmed,
    cancelled: common.cancelled,
    completed: common.completed,
  }
  return labels[status] ?? status
}

export function eventTypeLabel(type: string, language?: string | null) {
  const t = getDictionary(language)
  const labels: Record<string, string> = {
    reservation: t.events.newReservation,
    cancellation: t.events.bookingCancelled,
    status_change: t.events.appointmentUpdated,
    reschedule: "Reschedule",
    note: "Note",
  }
  return labels[type] ?? type.replace("_", " ")
}
