export type Locale = "en" | "ar"

export function normalizeLocale(language?: string | null): Locale {
  return language === "ar" ? "ar" : "en"
}

export function dirForLocale(locale: Locale) {
  return locale === "ar" ? "rtl" : "ltr"
}

